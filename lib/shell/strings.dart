import 'dart:ui';

/// The few strings the app draws itself; everything else is the website's.
class Strings {
  Strings._(this._values);
  final Map<String, String> _values;

  static Strings of(Locale locale) => Strings._(_strings[tag(locale)]!);

  /// The strings for a website locale (`<html lang>`), English otherwise.
  static Strings forTag(String tag) =>
      Strings._(_strings[tag] ?? _strings['en']!);

  /// The website locale this app opens in and draws its own strings in.
  static String tag(Locale locale) => switch (locale.languageCode) {
    'zh'
        when locale.scriptCode == 'Hant' ||
            const {'TW', 'HK', 'MO'}.contains(locale.countryCode) =>
      'zh-TW',
    'zh' => 'zh-CN',
    'ja' || 'ko' => locale.languageCode,
    _ => 'en',
  };

  String operator [](String key) => _values[key] ?? _strings['en']![key]!;

  String format(String key, Map<String, Object> values) => values.entries.fold(
    this[key],
    (text, entry) => text.replaceAll('{${entry.key}}', '${entry.value}'),
  );
}

